//! The table generator, shared by `build.rs` and the crate's tests.
//!
//! `build.rs` includes this module with `#[path]` and calls [`generate_table`];
//! the tests call the same function against temporary fixture trees. Keeping one
//! implementation means the drift checks tested here are exactly the ones that
//! run during a real build — a test-only reimplementation would be free to
//! disagree with what ships.
//!
//! The module is written against `crate::scheme` and `crate::sha256` so it
//! compiles in both the library crate and the build-script crate, where both are
//! top-level modules.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use crate::scheme;
use crate::sha256;

/// Reads the vendored trees, verifies them against the freeze manifest, and
/// returns the body of the generated `builtins.rs`.
///
/// `lib_count` and `deps_count` are the numbers of builtins the two trees must
/// hold. The build passes [`scheme::BUILTIN_FILE_COUNT`] and
/// [`scheme::DEPS_FILE_COUNT`]; tests pass their fixture's counts. Both are
/// checked last, after every file-level check, so a drift report names the file
/// that changed instead of only the total.
///
/// The two counts are deliberately separate. A single total over both trees
/// would let one gain a file while the other lost one and still balance; each
/// tree is what Node's js2c is handed, so each tree is what stays pinned.
///
/// Verification is not optional: the table is frozen data, so a tree that no
/// longer matches `LIBJS.sha256` must fail the build instead of silently
/// embedding drifted JavaScript. One manifest covers both trees because each
/// entry is keyed by its js2c path, so `lib/fs.js` and `deps/undici/undici.js`
/// are checked by the same `sha256sum -c` the shell gate runs.
pub fn generate_table(
    lib_dir: &Path,
    deps_dir: &Path,
    manifest_path: &Path,
    lib_count: usize,
    deps_count: usize,
) -> Result<String, String> {
    let expected = read_sha_manifest(manifest_path)?;
    let files = scheme::collect_all(lib_dir, deps_dir, lib_count, deps_count)?;

    for file in &files {
        let bytes = fs::read(&file.path)
            .map_err(|error| format!("cannot read {}: {error}", file.path.display()))?;
        let recorded = expected
            .get(&file.js2c_path)
            .ok_or_else(|| format!("{} is not listed in LIBJS.sha256", file.js2c_path))?;
        let actual = sha256::digest_hex(&bytes);
        if &actual != recorded {
            return Err(format!(
                "{} does not match LIBJS.sha256 (recorded {recorded}, found {actual}); \
                 vendor/libnode-js must stay byte-identical to Node",
                file.js2c_path
            ));
        }
    }

    // A manifest entry with no file behind it means a tree lost a builtin.
    // Naming the file is what makes the failure actionable.
    if let Some(orphan) = expected
        .keys()
        .find(|path| !files.iter().any(|file| &file.js2c_path == *path))
    {
        return Err(format!(
            "LIBJS.sha256 lists `{orphan}`, which is not in the vendored trees under {}",
            lib_dir
                .parent()
                .map(|parent| parent.display().to_string())
                .unwrap_or_else(|| lib_dir.display().to_string())
        ));
    }

    Ok(render(&files))
}

/// Renders the table. Split out so tests can compare output across runs for
/// determinism without re-reading the tree.
fn render(files: &[scheme::SourceFile]) -> String {
    let mut out = String::with_capacity(8 << 20);
    out.push_str(
        "// @generated by rn-js2c/build.rs from vendor/libnode-js/lib and \
         vendor/libnode-js/deps.\n\
         // Do not edit: change the generator or the vendored trees instead.\n\n",
    );

    out.push_str("/// Every builtin, ordered by id.\n");
    out.push_str(&format!(
        "static BUILTINS: [Builtin; {}] = [\n",
        files.len()
    ));
    for file in files {
        let id = &file.id;
        let kind = scheme::kind_for(id, &file.js2c_path);
        let category = scheme::category_for(id);
        // `include_str!` keeps this generated Rust small and lets rustc intern
        // the bytes once, instead of parsing a multi-megabyte literal. The path
        // is built from two fixed strings rather than an absolute path, so the
        // generated file is identical on every machine and in every checkout.
        // The directory follows from the tree the file was read from, so a
        // `deps/` builtin is included from `vendor/libnode-js/deps`.
        let relative = format!("{}/{}", file.tree.vendor_relative(), file.tree_relative);
        out.push_str(&format!(
            "    Builtin {{ id: {id:?}, kind: BuiltinKind::{kind:?}, category: \
             BuiltinCategory::{category:?}, source: include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \
             \"/{relative}\")) }},\n"
        ));
    }
    out.push_str("];\n\n");

    // A sorted slice id -> index, so lookups are one binary search over `&str`
    // with no allocation.
    out.push_str("/// Builtin ids in table order, for binary search.\n");
    out.push_str(&format!("static IDS: [&str; {}] = [\n", files.len()));
    for file in files {
        out.push_str(&format!("    {:?},\n", file.id));
    }
    out.push_str("];\n");

    out
}

/// Parses `LIBJS.sha256`, the format `sha256sum -c` writes:
/// `<64 hex digits><two spaces><path>`.
pub fn read_sha_manifest(path: &Path) -> Result<BTreeMap<String, String>, String> {
    let text = fs::read_to_string(path)
        .map_err(|error| format!("cannot read {}: {error}", path.display()))?;
    parse_sha_manifest(&text).map_err(|error| format!("{}: {error}", path.display()))
}

/// Parses manifest text. Separate from [`read_sha_manifest`] so tests can feed
/// fixtures directly.
pub fn parse_sha_manifest(text: &str) -> Result<BTreeMap<String, String>, String> {
    let mut entries = BTreeMap::new();

    for (number, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let (digest, name) = line
            .split_once("  ")
            .ok_or_else(|| format!("line {}: expected `<digest>  <path>`", number + 1))?;
        if digest.len() != 64 || !digest.bytes().all(|b| b.is_ascii_hexdigit()) {
            return Err(format!(
                "line {}: `{digest}` is not a SHA-256 digest",
                number + 1
            ));
        }
        if entries
            .insert(name.to_string(), digest.to_ascii_lowercase())
            .is_some()
        {
            return Err(format!("line {}: duplicate entry for `{name}`", number + 1));
        }
    }

    Ok(entries)
}

/// Writes `contents` to `dest` only when it differs, so a no-op rebuild does not
/// touch the generated file and does not force dependents to recompile.
pub fn write_if_changed(dest: &Path, contents: &[u8]) -> std::io::Result<()> {
    if let Ok(existing) = fs::read(dest) {
        if existing == contents {
            return Ok(());
        }
    }
    fs::write(dest, contents)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    /// Builds a throwaway tree that looks like `vendor/libnode-js`, including
    /// the `deps/` half, so the generator's two-tree path is what the tests
    /// exercise rather than a single-directory approximation of it.
    struct Fixture {
        root: PathBuf,
    }

    impl Fixture {
        /// A fixture whose `lib/` holds `files` and whose `deps/` is empty.
        fn new(name: &str, files: &[(&str, &str)]) -> Self {
            Self::with_deps(name, files, &[])
        }

        /// A fixture with both trees populated. Every file, in either tree, is
        /// recorded in the one manifest under its js2c path, exactly as the real
        /// vendored tree does.
        fn with_deps(name: &str, files: &[(&str, &str)], deps: &[(&str, &str)]) -> Self {
            let root =
                std::env::temp_dir().join(format!("rn-js2c-fixture-{}-{name}", std::process::id()));
            let _ = fs::remove_dir_all(&root);
            fs::create_dir_all(root.join("lib")).expect("create fixture lib dir");
            fs::create_dir_all(root.join("deps")).expect("create fixture deps dir");

            let mut manifest = String::new();
            for (tree, entries) in [("lib", files), ("deps", deps)] {
                for (relative, contents) in entries {
                    let path = root.join(tree).join(relative);
                    if let Some(parent) = path.parent() {
                        fs::create_dir_all(parent).expect("create fixture subdir");
                    }
                    fs::write(&path, contents).expect("write fixture file");
                    manifest.push_str(&format!(
                        "{}  {tree}/{relative}\n",
                        sha256::digest_hex(contents.as_bytes())
                    ));
                }
            }
            fs::write(root.join("LIBJS.sha256"), manifest).expect("write fixture manifest");
            Self { root }
        }

        fn lib(&self) -> PathBuf {
            self.root.join("lib")
        }

        fn deps(&self) -> PathBuf {
            self.root.join("deps")
        }

        fn manifest(&self) -> PathBuf {
            self.root.join("LIBJS.sha256")
        }

        /// Generates against this fixture, taking the counts from the trees it
        /// was built with. Tests that want a count mismatch pass their own.
        fn generate(&self, lib_count: usize, deps_count: usize) -> Result<String, String> {
            generate_table(
                &self.lib(),
                &self.deps(),
                &self.manifest(),
                lib_count,
                deps_count,
            )
        }
    }

    impl Drop for Fixture {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.root);
        }
    }

    #[test]
    fn generates_a_row_per_file_in_id_order() {
        let fixture = Fixture::new(
            "happy",
            &[
                ("fs.js", "module.exports = 1;"),
                ("internal/util.js", "exports.x = 2;"),
            ],
        );

        let files = scheme::collect_all(&fixture.lib(), &fixture.deps(), 2, 0).expect("collect");
        assert_eq!(
            files.iter().map(|f| f.id.as_str()).collect::<Vec<_>>(),
            ["fs", "internal/util"]
        );
        let table = render(&files);
        assert!(table.contains(r#"id: "fs""#), "{table}");
        assert!(table.contains("BuiltinKind::Function"), "{table}");
        assert!(table.contains("BuiltinCategory::Core"), "{table}");
        assert!(table.contains("BuiltinCategory::Internal"), "{table}");
        // `fs` sorts before `internal/util`, so it must render first.
        assert!(
            table.find(r#"id: "fs""#) < table.find(r#"id: "internal/util""#),
            "{table}"
        );
    }

    #[test]
    fn a_deps_builtin_renders_from_the_deps_directory() {
        // The generated row has to include the file from the tree it actually
        // came from. A `deps/` builtin emitted with the `lib/` root would fail to
        // compile, but only after the whole table had been built, so pin the path
        // here where the message is specific.
        let fixture = Fixture::with_deps(
            "deps-row",
            &[("fs.js", "a")],
            &[("undici/undici.js", "module.exports = {};")],
        );

        let files = scheme::collect_all(&fixture.lib(), &fixture.deps(), 1, 1).expect("collect");
        let table = render(&files);
        assert!(
            table.contains(r#"id: "internal/deps/undici/undici""#),
            "{table}"
        );
        assert!(
            table.contains("vendor/libnode-js/deps/undici/undici.js"),
            "the deps row must include from the deps tree: {table}"
        );
        assert!(
            !table.contains("vendor/libnode-js/lib/undici/undici.js"),
            "the deps row must not be resolved against lib/: {table}"
        );
        assert!(
            table.contains("BuiltinCategory::Internal"),
            "a deps builtin is internal: {table}"
        );
    }

    #[test]
    fn generation_is_deterministic() {
        let fixture = Fixture::with_deps(
            "deterministic",
            &[
                ("fs.js", "a"),
                ("assert.js", "b"),
                ("internal/util.js", "c"),
            ],
            &[("undici/undici.js", "d")],
        );
        let first = scheme::collect_all(&fixture.lib(), &fixture.deps(), 3, 1).expect("collect");
        let second = scheme::collect_all(&fixture.lib(), &fixture.deps(), 3, 1).expect("collect");
        assert_eq!(render(&first), render(&second));

        // Rendering must not depend on directory iteration order, so collect
        // twice after touching the files in opposite order.
        fs::write(fixture.lib().join("fs.js"), "a").expect("rewrite");
        let third = scheme::collect_all(&fixture.lib(), &fixture.deps(), 3, 1).expect("collect");
        assert_eq!(render(&first), render(&third));
    }

    #[test]
    fn edited_vendored_file_fails_generation() {
        // The core drift case: a builtin changes on disk while the manifest still
        // records the old bytes. Generation must refuse, naming the file.
        let fixture = Fixture::new("edited", &[("fs.js", "original")]);
        fs::write(fixture.lib().join("fs.js"), "edited").expect("edit builtin");

        let error = fixture
            .generate(1, 0)
            .expect_err("an edited builtin must fail generation");
        assert!(error.contains("lib/fs.js"), "{error}");
        assert!(error.contains("does not match LIBJS.sha256"), "{error}");
    }

    #[test]
    fn an_edited_deps_file_fails_generation_too() {
        // The deps tree is frozen by the same mechanism, so the check cannot be
        // a `lib/`-only loop that happens to also walk `deps/`.
        let fixture = Fixture::with_deps(
            "edited-deps",
            &[("fs.js", "a")],
            &[("undici/undici.js", "original")],
        );
        fs::write(fixture.deps().join("undici/undici.js"), "edited").expect("edit bundle");

        let error = fixture
            .generate(1, 1)
            .expect_err("an edited deps builtin must fail generation");
        assert!(error.contains("deps/undici/undici.js"), "{error}");
        assert!(error.contains("does not match LIBJS.sha256"), "{error}");
    }

    #[test]
    fn file_added_without_regenerating_the_manifest_fails() {
        let fixture = Fixture::new("added", &[("fs.js", "a")]);
        fs::write(fixture.lib().join("new_builtin.js"), "b").expect("add builtin");

        let error = fixture
            .generate(2, 0)
            .expect_err("an unlisted builtin must fail generation");
        assert!(error.contains("lib/new_builtin.js"), "{error}");
        assert!(error.contains("not listed in LIBJS.sha256"), "{error}");
    }

    #[test]
    fn file_removed_but_still_listed_fails() {
        let fixture = Fixture::new("removed", &[("fs.js", "a"), ("gone.js", "b")]);
        fs::remove_file(fixture.lib().join("gone.js")).expect("remove builtin");

        let error = fixture
            .generate(1, 0)
            .expect_err("a listed-but-absent builtin must fail generation");
        assert!(error.contains("lib/gone.js"), "{error}");
        assert!(error.contains("is not in"), "{error}");
    }

    #[test]
    fn each_tree_count_is_enforced_separately() {
        // The counts are the invariant that makes the trees frozen in practice,
        // so a generation that only checked a combined total would let one tree
        // grow while the other shrank. Both directions are exercised, and neither
        // may be satisfied by the other's number.
        let fixture = Fixture::with_deps(
            "counts",
            &[("fs.js", "a"), ("zlib.js", "b")],
            &[("undici/undici.js", "c")],
        );

        fixture.generate(2, 1).expect("matching counts generate");
        let error = fixture
            .generate(2, 2)
            .expect_err("a wrong deps count must fail");
        assert!(error.contains("expected 2 builtin files"), "{error}");
        assert!(error.contains("deps"), "{error}");
        let error = fixture
            .generate(3, 1)
            .expect_err("a wrong lib count must fail");
        assert!(error.contains("expected 3 builtin files"), "{error}");
    }

    #[test]
    fn a_deps_file_only_behind_the_manifest_is_reported_as_missing() {
        // The orphan direction for the deps tree: removing the bundle without
        // touching the manifest must fail, and the message must name the js2c
        // path rather than an id, because that is what the manifest holds.
        let fixture = Fixture::with_deps(
            "orphan-deps",
            &[("fs.js", "a")],
            &[("undici/undici.js", "b")],
        );
        fs::remove_file(fixture.deps().join("undici/undici.js")).expect("remove bundle");

        let error = fixture
            .generate(1, 0)
            .expect_err("a listed-but-absent deps builtin must fail generation");
        assert!(error.contains("deps/undici/undici.js"), "{error}");
        assert!(error.contains("is not in"), "{error}");
    }

    #[test]
    fn unexcluded_es_module_fails_generation() {
        // Node's js2c embeds `.mjs` files as SourceTextModule; this crate does not
        // cover that yet, so a new `.mjs` must be loud instead of skipped.
        let fixture = Fixture::new("mjs", &[("fs.js", "a")]);
        fs::write(fixture.lib().join("extra.mjs"), "export {};").expect("add mjs");

        let error = scheme::collect(&fixture.lib(), scheme::BuiltinTree::Lib)
            .expect_err("an unexcluded .mjs must fail");
        assert!(error.contains("extra.mjs"), "{error}");
    }

    #[test]
    fn the_one_excluded_es_module_is_skipped() {
        // Mirrors `tools/js2c.cc`, which erases `lib/eslint.config_partial.mjs`
        // from the `.mjs` list before generating. It must not become a builtin.
        let fixture = Fixture::new("excluded-mjs", &[("fs.js", "a")]);
        fs::write(
            fixture.lib().join("eslint.config_partial.mjs"),
            "export {};",
        )
        .expect("add mjs");

        let files = scheme::collect(&fixture.lib(), scheme::BuiltinTree::Lib).expect("collect");
        assert_eq!(files.len(), 1);
        assert_eq!(files[0].id, "fs");
    }

    #[test]
    fn manifest_parser_rejects_bad_shapes() {
        assert!(
            parse_sha_manifest("abc  lib/fs.js\n").is_err(),
            "short digest"
        );
        assert!(
            parse_sha_manifest("zz  lib/fs.js\n").is_err(),
            "non-hex digest"
        );
        assert!(parse_sha_manifest("ab").is_err(), "no separator");
        assert!(
            parse_sha_manifest(&format!(
                "{}  a.js\n{}  a.js\n",
                "0".repeat(64),
                "1".repeat(64)
            ))
            .is_err(),
            "duplicate path"
        );
        assert_eq!(parse_sha_manifest("").expect("empty is valid").len(), 0);
    }

    #[test]
    fn write_if_changed_leaves_identical_content_alone() {
        let dir = std::env::temp_dir().join(format!("rn-js2c-wic-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).expect("create dir");
        let dest = dir.join("out.rs");

        write_if_changed(&dest, b"one").expect("first write");
        let first = fs::metadata(&dest)
            .and_then(|m| m.modified())
            .expect("mtime");
        std::thread::sleep(std::time::Duration::from_millis(10));
        write_if_changed(&dest, b"one").expect("no-op write");
        let second = fs::metadata(&dest)
            .and_then(|m| m.modified())
            .expect("mtime");
        assert_eq!(first, second, "an identical write must not touch the file");

        write_if_changed(&dest, b"two").expect("changed write");
        assert_eq!(fs::read(&dest).expect("read back"), b"two");

        let _ = fs::remove_dir_all(&dir);
    }
}
