//! Bun's text, value and stream-helper members, contributed to the `Bun` global.
//!
//! This crate is one contributor to `Bun`, through [`rn_bun_api::BunModule`]. It
//! does not create `Bun` and does not touch `rn-bun`, `rn-bun-members` or any
//! shared list; `tools/regen-bun-contributions.sh` discovers [`register`] and
//! calls it from the generated aggregator. See
//! `rustnode/docs/contributing-bun-members.md` for the contract.
//!
//! # What lives where
//!
//! The modules are split so the hard parts are testable without V8:
//!
//! * [`width`] — column measurement: a fused Unicode **17.0.0** table plus UAX #29
//!   grapheme clustering. It is what makes `stringWidth("👨‍👩‍👧‍👦")` two columns
//!   instead of eight. The Unicode question is answered in that module's docs and
//!   in [`width_tables`], which is generated by `tools/gen-width-tables.py`.
//! * [`ansi`] — escape-sequence parsing and the style state wrap/slice share.
//! * [`wrap`] and [`slice`] — the two ANSI-aware layout functions.
//! * [`semver`], [`html`], [`uuid`], [`timers`], [`buffers`] — pure logic.
//! * `values.js`, `streams.js`, `timers.js` and the sink factory in
//!   [`inspect`] — the members whose job is walking live object graphs or the
//!   stream protocol, where JavaScript is the layer Bun's own implementation sits
//!   at.
//!
//! Everything JS-facing is a few lines in `bindings`, so no algorithm is
//! duplicated between Rust and JavaScript.
//!
//! # Why `inspect` is not `util.inspect`
//!
//! `Bun.inspect` looks like `util.inspect` and is not: Bun is multiline by
//! default with trailing commas and double-quoted strings, and its
//! depth-exceeded marker is `[Object ...]` where Node's is `[Object]`. Node's own
//! `lib/internal/util/inspect.js` is vendored and unmodifiable, and its output
//! differs on the first object, so the format is implemented directly.
//!
//! # Members this crate does not own
//!
//! `Bun.nanoseconds` is `rn-bun-time`'s, so it is neither installed nor deferred
//! here — a deferral is a statement that this crate *owes* the member, and it does
//! not.

