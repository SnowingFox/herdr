/// Every member this crate installs on `Bun`.
///
/// Each name is checked against the object [`Text::install`] really builds, in
/// both directions, by [`rn_bun_api::BunRegistry`] before `Bun` is published, and
/// against Bun 1.4.4's real surface by the gate. `Bun.semver` is one entry here
/// even though it is an object rather than a function, because the surface is a
/// property space and not a function list.
pub const MEMBERS: &[&str] = &[
    "ArrayBufferSink",
    "allocUnsafe",
    "concatArrayBuffers",
    "deepEquals",
    "deepMatch",
    "escapeHTML",
    "indexOfLine",
    "inspect",
    "randomUUIDv5",
    "randomUUIDv7",
    "readableStreamToArray",
    "readableStreamToArrayBuffer",
    "readableStreamToBlob",
    "readableStreamToBytes",
    "readableStreamToFormData",
    "readableStreamToJSON",
    "readableStreamToText",
    "semver",
    "shrink",
    "sleep",
    "sleepSync",
    "sliceAnsi",
    "stringWidth",
    "stripANSI",
    "wrapAnsi",
];

/// Members in this group that this crate does not install yet.
///
/// Empty, and that is a measurement rather than a placeholder: every member the
/// text/misc group owns is installed and compared against Bun 1.4.4. The two that
/// are not here — `Bun.nanoseconds` and `Bun.main` — belong to other crates.
pub const DEFERRED: &[(&str, &str)] = &[];

/// This crate's contribution to `Bun`.
pub struct Text;

impl BunModule for Text {
    fn contributor(&self) -> &'static str {
        "rn-bun-text"
    }

    fn members(&self) -> &'static [&'static str] {
        MEMBERS
    }

    fn deferred(&self) -> &'static [(&'static str, &'static str)] {
        DEFERRED
    }

    fn install<'s>(
        &self,
        scope: &mut v8::PinScope<'s, '_>,
        target: v8::Local<'s, v8::Object>,
    ) -> Result<(), String> {
        bindings::install(scope, target)
    }
}

/// Registers this crate with the Bun contribution registry.
///
/// `tools/regen-bun-contributions.sh` discovers this declaration and calls it
/// from the generated aggregator, so this crate never edits a shared file.
pub fn register(registry: &mut rn_bun_api::BunRegistry) -> Result<(), String> {
    registry.register_module(Text)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_declared_member_is_one_bun_really_has() {
        // The surface file is Bun 1.4.4's own member list. A name invented here
        // would be refused by the gate, so the same check runs first as a test.
        let surface: serde_json::Value =
            serde_json::from_str(include_str!("../../../tools/bun-surface.json"))
                .expect("bun-surface.json is valid JSON");
        // `tools/bun-surface.json` keys its `members` by property name, each with
        // a `kind` and `tier`.
        let known = surface["members"].as_object().expect("members object");
        for member in MEMBERS {
            assert!(
                known.contains_key(*member),
                "Bun.{member} is not a member of Bun 1.4.4; the gate refuses fabricated names"
            );
        }
    }

    #[test]
    fn the_declaration_is_a_partition() {
        // No name may be both installed and deferred, and every deferral must
        // carry a reason: the registry enforces both, and so does this.
        for member in MEMBERS {
            assert!(
                !DEFERRED.iter().any(|(name, _)| name == member),
                "Bun.{member} is both installed and deferred"
            );
        }
        for (member, reason) in DEFERRED {
            assert!(
                !reason.trim().is_empty(),
                "Bun.{member} is deferred with no reason"
            );
        }
    }

    #[test]
    fn registering_contributes_every_member() {
        let mut registry = rn_bun_api::BunRegistry::new();
        register(&mut registry).expect("registration succeeds");
        let declared: Vec<&str> = registry
            .declarations()
            .iter()
            .map(|declaration| declaration.member.as_str())
            .collect();
        assert_eq!(declared.len(), MEMBERS.len());
        for member in MEMBERS {
            assert!(declared.contains(member), "Bun.{member} was not registered");
        }
        assert!(
            registry.deferrals().is_empty(),
            "nothing in this crate is deferred"
        );
    }

    #[test]
    fn this_crate_does_not_claim_nanoseconds() {
        // `Bun.nanoseconds` is `rn-bun-time`'s. Claiming it here would make the
        // registry reject one of the two crates at startup.
        assert!(
            !MEMBERS.contains(&"nanoseconds"),
            "rn-bun-time owns Bun.nanoseconds"
        );
    }
}
